"""Read-only Capital portfolio deployment verification, bound to a reviewed commit.

Prepare without network (the commit may be omitted while review is pending):
  python3 -B scripts/verify_deployment.py --base-url https://ult666666.github.io \
      --output qa-local/v4-0/portfolio-prepared.json

After the reviewed commit has been deployed, add --commit FULL_HEAD --run.
The existing _site directory must already have been built. This verifier never
builds, edits or publishes the site; its only persistent output is a new receipt.
"""
