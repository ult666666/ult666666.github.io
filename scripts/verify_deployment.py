def fetch(name, url, expected, deadline):
    remaining = deadline - time.monotonic()
    if remaining <= 0:
        raise ValueError('Verification deadline exceeded')
    scheme = urlsplit(url).scheme
    if scheme not in ('http', 'https'):
        raise ValueError('Unsupported verification transport')
    maximum_time = min(30, remaining)
    with tempfile.TemporaryDirectory(prefix='portfolio-verify-http-') as directory:
        path = Path(directory) / 'response'
        command = ['curl', '-q', '--silent', '--show-error', '--globoff', '--proto', '=' + scheme,
                   '--connect-timeout', str(min(10, maximum_time)), '--max-time', str(maximum_time),
                   '--max-filesize', str(MAX_RESPONSE_BYTES), '--output', str(path),
                   '--write-out', '%{json}', '--url', url]
        if scheme == 'https':
            command += ['--tlsv1.2']
        process = subprocess.run(command, capture_output=True, text=True, timeout=maximum_time + 5)
        try:
            meta = json.loads(process.stdout)
        except json.JSONDecodeError:
            meta = {}
        with path.open('rb') if path.exists() else tempfile.TemporaryFile() as handle:
            body = handle.read(MAX_RESPONSE_BYTES + 1)
        mime = (meta.get('content_type') or '').split(';', 1)[0].strip().lower()
        suffix = '.html' if name == 'root-alias' else Path(name).suffix
        mime_ok = mime in ({'text/plain', 'application/octet-stream'} if name == '.nojekyll' else MIME.get(suffix, set()))
        tls_used = scheme == 'https'
        tls_ok = not tls_used or meta.get('ssl_verify_result') == 0
        passed = (process.returncode == 0 and tls_ok and meta.get('http_code') == 200
                  and meta.get('url_effective') == url and mime_ok
                  and len(body) <= MAX_RESPONSE_BYTES and file_record(body) == expected)
        return {
            'name': name, 'url': url, 'finalUrl': meta.get('url_effective'), 'method': 'GET',
            'status': meta.get('http_code'), 'curlExitCode': process.returncode,
            'tlsUsed': tls_used, 'ordinaryCertificateVerification': tls_ok if tls_used else None,
            'mime': mime, 'mimeAccepted': mime_ok, **file_record(body), 'expected': expected,
            'passed': passed, 'error': process.stderr.strip()[:4096] or None,
        }, body


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--base-url', required=True, help='HTTPS origin or HTTP loopback origin')
    parser.add_argument('--commit', help='Expected full reviewed HEAD; required with --run')
    parser.add_argument('--output', type=Path, help='Fresh receipt path; required with --run')
    parser.add_argument('--run', action='store_true', help='Run bounded HTTP checks after exact-commit deployment')
    parser.add_argument('--deadline-seconds', type=int, default=180)
    args = parser.parse_args()
    try:
        base = origin(args.base_url)
        if args.commit is not None and re.fullmatch(r'[a-f0-9]{40}', args.commit) is None:
            raise ValueError('--commit must be the complete lowercase 40-character reviewed commit')
        if args.run and (args.commit is None or args.output is None):
            raise ValueError('--run requires --commit and a fresh --output receipt')
        if not 30 <= args.deadline_seconds <= 600:
            raise ValueError('The deadline must be between 30 and 600 seconds')
        if args.output is not None:
            args.output = safe_path(args.output)
            if args.output.exists():
                raise ValueError('Preserve prior receipts; select a fresh output path')
            if args.output.is_relative_to(ROOT) and not args.output.is_relative_to(ROOT / 'qa-local'):
                raise ValueError('Receipts inside the source checkout must be under qa-local')
    except ValueError as error:
        parser.error(str(error))

    started = time.monotonic()
    report = {
        'schema': 1, 'purpose': 'capital-portfolio-deployment-consistency', 'status': 'fail',
        'startedAtUtc': datetime.now(timezone.utc).isoformat(), 'baseUrl': base,
        'expectedCommit': args.commit, 'networkRequested': args.run,
        'applicationVersion': '4.0.0', 'tlsVerification': True, 'tlsUsed': args.run and urlsplit(base).scheme == 'https',
        'transport': 'System curl with configuration files disabled, no redirects and ordinary certificate/hostname verification. HTTP is allowed only on loopback.',
        'bounds': {'maxVisitorSources': MAX_VISITOR_SOURCES, 'maxResponseBytes': MAX_RESPONSE_BYTES,
                   'maxTotalTransferBytes': MAX_TOTAL_TRANSFER_BYTES, 'deadlineSeconds': args.deadline_seconds},
        'checks': [], 'semanticChecks': [], 'networkRequests': 0,
        'limitations': ['Byte and semantic checks describe the recorded deployment, not future uptime.',
                       'Browser interaction and application calculations have separate verification.',
                       'Preparation without --commit does not certify reviewed source or deployment.',
                       'An unavailable .nojekyll marker is excluded from required visitor checks; a served marker must be empty.'],
    }
    try:
        before, staged = capture(args.commit)
        report['bounds']['visitorSources'] = before['visitorSourceCount']
        report['sourceBinding'] = {'before': before, 'unchangedDuringRun': False}
        report['stagedSemanticChecks'] = semantic_checks(staged)
        if not all(check['passed'] for check in report['stagedSemanticChecks']):
            raise ValueError('Staged semantic checks failed; no network verification was started')
        if args.run:
            total = 0
            bodies = {}
            items = [(name, base + '/' + quote(name, safe='/'), expected)
                     for name, expected in before['deploymentFiles'].items() if name != '.nojekyll']
            items.append(('root-alias', base + '/', before['deploymentFiles']['index.html']))
            for name, url, expected in items:
                result, body = fetch(name, url, expected, started + args.deadline_seconds)
                report['checks'].append(result)
                report['networkRequests'] += 1
                bodies[name] = body
                total += len(body)
                if total > MAX_TOTAL_TRANSFER_BYTES:
                    raise ValueError('Total response bytes exceeded the verification budget')
            marker, _ = fetch('.nojekyll', base + '/.nojekyll', before['deploymentFiles']['.nojekyll'], started + args.deadline_seconds)
            report['networkRequests'] += 1
            marker.update(role='Generated deployment marker', includedInVisitorPassCount=False,
                          available=marker['status'] == 200,
                          interpretation='Unavailable markers do not fail visitor verification; served markers must match.')
            report['deploymentMarker'] = marker
            report['semanticChecks'] = semantic_checks(bodies)
        else:
            report['semanticChecks'] = report['stagedSemanticChecks']
        after, _ = capture(args.commit)
        report['sourceBinding']['unchangedDuringRun'] = before == after
        marker = report.get('deploymentMarker', {})
        passed = (before == after and all(check['passed'] for check in report['checks'])
                  and all(check['passed'] for check in report['semanticChecks'])
                  and (not marker.get('available') or marker.get('passed')))
        report['status'] = ('pass' if args.run else 'prepared') if passed else 'fail'
    except (ValueError, OSError, subprocess.SubprocessError, UnicodeError) as error:
        report['error'] = str(error)
    report['counts'] = {
        'visitorSources': report.get('sourceBinding', {}).get('before', {}).get('visitorSourceCount'),
        'generatedManifests': 1, 'rootAliases': 1,
        'requiredHttpRequests': len(report['checks']), 'requiredHttpPassed': sum(c['passed'] for c in report['checks']),
        'semanticChecks': len(report['semanticChecks']), 'semanticChecksPassed': sum(c['passed'] for c in report['semanticChecks']),
        'deploymentMarkerRequests': int('deploymentMarker' in report),
    }
    report['finishedAtUtc'] = datetime.now(timezone.utc).isoformat()
    report['elapsedSeconds'] = time.monotonic() - started
    if args.output is not None:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        with args.output.open('x', encoding='utf-8') as stream:
            json.dump(report, stream, indent=2, allow_nan=False)
            stream.write('\n')
        print(json.dumps({'status': report['status'], 'counts': report['counts'], 'networkRequests': report['networkRequests'],
                          'error': report.get('error'), 'receipt': str(args.output), 'sha256': digest(args.output.read_bytes())}))
    else:
        print(json.dumps(report, indent=2, allow_nan=False))
    return 0 if report['status'] in ('pass', 'prepared') else 1


if __name__ == '__main__':
    raise SystemExit(main())
